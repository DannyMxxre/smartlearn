package ru.smartlearn.mentor.question;

import org.springframework.stereotype.Component;
import ru.smartlearn.mentor.dialog.Role;

import java.util.List;
import java.util.Map;

/**
 * Банк заданий диагностики.
 * По четыре задания на роль: постановка, проверка, практика и границы.
 */
@Component
public class QuestionBank {

	private final Map<Role, List<Question>> questions = Map.of(
			Role.ANALYST, List.of(
					new Question(
							"a-task",
							"Постановка задачи модели",
							"Стейкхолдер прислал сырую расшифровку созвона на 10 минут. Как попросишь ИИ превратить её в user stories с критериями приёмки и что проверишь сам, прежде чем отдать команде?",
							"Есть ли структура промпта и ручная проверка критериев приёмки."
					),
					new Question(
							"a-check",
							"Проверка противоречий",
							"ИИ дописал раздел требований, который противоречит условию из начала документа. Как это поймать и что изменишь в промпте или процессе, чтобы противоречие всплывало сразу?",
							"Есть ли сверка с исходным требованием, а не слепое принятие текста."
					),
					new Question(
							"a-practice",
							"Практический разбор заметки",
							"Практика. Заметка: «Клиенты лотереи должны сами видеть статус выплаты, операторы больше не копируют его из трёх систем. Юристам нужно согласие. Срок — до пятницы, интеграция неясна.» Напиши промпт или сразу результат: акторы, цели и открытые вопросы.",
							"Выделены ли акторы, цели и то, что ещё неизвестно."
					),
					new Question(
							"a-limits",
							"Границы применения",
							"В каких аналитических задачах ИИ лучше не использовать или использовать только с ограничениями? Назови риски: персональные данные, галлюцинации, ответственность за требование.",
							"Названы ли данные, выдуманные факты и ответственность аналитика."
					)
			),
			Role.DEVELOPER, List.of(
					new Question(
							"d-bug",
							"Разбор падения и ревью патча",
							"Тест падает в чужом сервисе. Как используешь ИИ, чтобы найти причину и предложить патч, и какой чеклист ревью не даст принять плохой diff?",
							"Есть ли гипотеза, проверка и ревью diff, а не слепое принятие патча."
					),
					new Question(
							"d-api",
							"Работа с несуществующим API",
							"Модель предложила метод Spring, которого нет в твоей версии. Как выстроишь работу с инструментом, чтобы таких советов стало меньше?",
							"Есть ли привязка к версии, документации или коду проекта."
					),
					new Question(
							"d-practice",
							"Промпт на рабочую ручку",
							"Практика. Напиши промпт, по которому ИИ сделает REST-ручку на Spring Boot: валидация входа, понятные ошибки и тест. Что проверишь в ответе модели до коммита?",
							"Промпт конкретный, а перед коммитом есть проверка кода и теста."
					),
					new Question(
							"d-secrets",
							"Секреты и данные",
							"Что нельзя отправлять в промпт и в контекст агента? Как отделишь учебный пример от секретов и данных продакшена?",
							"Секреты и прод-данные не попадают в промпт, пример обезличен."
					)
			)
	);

	/**
	 * Возвращает задания выбранной роли в фиксированном порядке.
	 *
	 * @param role роль сотрудника
	 * @return четыре задания
	 */
	public List<Question> forRole(Role role) {
		return questions.get(role);
	}
}
