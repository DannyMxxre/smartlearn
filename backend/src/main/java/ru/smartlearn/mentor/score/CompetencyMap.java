package ru.smartlearn.mentor.score;

import org.springframework.stereotype.Component;
import ru.smartlearn.mentor.dialog.Role;

import java.util.List;

/**
 * Карта компетенций и бонусные практические кейсы.
 * Тексты собраны здесь, чтобы править рубрику без остального сценария.
 */
@Component
public class CompetencyMap {

	private static final String SCALE = """
			0 — нет сути, отписка или общие слова без действия
			1 — идея есть, но нет проверки результата
			2 — конкретные действия и способ проверить качество
			3 — приём, проверка и осознанное ограничение (данные, галлюцинации, ответственность)
			""";

	/**
	 * Возвращает пять компетенций роли.
	 *
	 * @param role роль сотрудника
	 * @return карта в порядке диалога
	 */
	public List<Competency> forRole(Role role) {
		if (role == Role.ANALYST) {
			return analyst();
		}
		return developer();
	}

	/**
	 * Ищет компетенцию по коду.
	 *
	 * @param role роль сотрудника
	 * @param id код компетенции
	 * @return компетенция
	 */
	public Competency byId(Role role, String id) {
		for (Competency competency : forRole(role)) {
			if (competency.id().equals(id)) {
				return competency;
			}
		}
		throw new IllegalArgumentException("Нет компетенции " + id);
	}

	/**
	 * Возвращает два практических кейса после основной диагностики.
	 *
	 * @param role роль сотрудника
	 * @return задания в порядке показа
	 */
	public List<BonusTask> bonuses(Role role) {
		if (role == Role.ANALYST) {
			return List.of(
					new BonusTask(
							"a-practice",
							"a-workflow",
							"Практический разбор заметки",
							"Практика. Заметка: «Клиенты лотереи должны сами видеть статус выплаты, операторы больше не копируют его из трёх систем. Юристам нужно согласие. Срок — до пятницы, интеграция неясна.» Напиши промпт или сразу результат: акторы, цели и открытые вопросы. Как проверишь, что ничего не додумано?"
					),
					new BonusTask(
							"a-check",
							"a-validation",
							"Проверка противоречий",
							"Практика. ИИ дописал раздел требований, который противоречит условию из начала документа. Как это поймать и что изменишь в промпте, чтобы противоречие всплывало сразу?"
					)
			);
		}
		return List.of(
				new BonusTask(
						"d-practice",
						"d-prompts",
						"Промпт на рабочую ручку",
						"Практика. Напиши промпт, по которому ИИ сделает REST-ручку на Spring Boot: валидация входа, понятные ошибки и тест. Что проверишь в ответе модели до коммита?"
				),
				new BonusTask(
						"d-bug",
						"d-verify",
						"Разбор падения и ревью патча",
						"Практика. Тест падает в чужом сервисе. Как используешь ИИ, чтобы найти причину и предложить патч, и какой чеклист ревью не даст принять плохой diff?"
				)
		);
	}

	/**
	 * Собирает карту аналитика.
	 *
	 * @return пять компетенций
	 */
	private List<Competency> analyst() {
		return List.of(
				competency("a-prompts", "Формулирование задач и промптов",
						"Возьми сырую заметку стейкхолдера. Как сформулируешь промпт, чтобы получить user story с критериями приёмки, и что проверишь сам перед передачей команде?",
						"Ждём структуру промпта под аналитический артефакт и ручную проверку."),
				competency("a-validation", "Критическая проверка результата",
						"Модель дописала требование, которого не было в источнике. Как поймаешь выдумку или противоречие и что изменишь в следующем запросе?",
						"Ждём сверку с источником, а не принятие текста как есть."),
				competency("a-workflow", "Применение ИИ в рабочем процессе",
						"На каком шаге работы с требованиями, процессом или данными ты подключаешь ИИ? Что подаёшь на вход и что считаешь готовым выходом?",
						"Ждём повторяемый шаг, а не разовый черновик."),
				competency("a-limits", "Ограничения и границы применимости",
						"Где в аналитической работе ИИ лучше не использовать? Назови риски: персональные данные, галлюцинации и ответственность за требование.",
						"Ждём конкретные границы, а не общее «осторожно»."),
				competency("a-iterate", "Итерации и доработка контекста",
						"Ответ модели вышел слабым. Какой контекст добавишь во второй запрос и как поймёшь, что правка помогла?",
						"Ждём цикл «результат, проверка, новый промпт», а не один запрос.")
		);
	}

	/**
	 * Собирает карту разработчика.
	 *
	 * @return пять компетенций
	 */
	private List<Competency> developer() {
		return List.of(
				competency("d-prompts", "Промптинг под задачи разработки",
						"Как попросишь ИИ сделать правку в коде? Что передашь про версию стека, ограничение и формат diff?",
						"Ждём привязку к стеку и формату результата, а не «напиши метод»."),
				competency("d-verify", "Верификация сгенерированного кода",
						"Модель предложила патч. Как проверишь, что он не ломает поведение: тесты, ревью diff и что ещё?",
						"Ждём проверку кода, а не слепое принятие патча."),
				competency("d-workflow", "ИИ в ежедневной разработке",
						"В какой ежедневной задаче ИИ уже стоит внутри процесса, а не разовым чатом? Что на входе и что проверяешь на выходе?",
						"Ждём встроенный шаг с проверкой, а не случайный вопрос в чат."),
				competency("d-limits", "Где ИИ использовать опасно",
						"Где в разработке ИИ использовать нельзя или опасно? Затронь секреты, прод-данные и советы про API, которого нет в проекте.",
						"Ждём запрет на секреты и отказ от несуществующего API."),
				competency("d-iterate", "Уточнение контекста и итерации",
						"Первый diff не подошёл. Как уточнишь контекст для следующей итерации и как проверишь, что стало лучше?",
						"Ждём уточнение контекста и повторную проверку, а не новый слепой запрос.")
		);
	}

	/**
	 * Собирает компетенцию с общей шкалой 0–3.
	 *
	 * @param id код
	 * @param title название
	 * @param prompt стартовый вопрос
	 * @param criteria что именно смотреть в ответе
	 * @return компетенция
	 */
	private Competency competency(String id, String title, String prompt, String criteria) {
		return new Competency(id, title, prompt, criteria + "\n" + SCALE);
	}
}
