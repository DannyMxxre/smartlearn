package ru.smartlearn.mentor.dialog;

/**
 * Уровень владения ИИ-инструментами.
 * Назначается только по сумме баллов, не по формулировке модели.
 */
public enum Level {

	/** Почти нет рабочего приёма. */
	NOVICE("Новичок"),

	/** Есть отдельные попытки, без устойчивой проверки. */
	BASIC("Базовый"),

	/** Приём и проверка уже есть, часть тем сырая. */
	CONFIDENT("Уверенный"),

	/** Постановка задачи, проверка и границы держатся вместе. */
	ADVANCED("Продвинутый");

	private final String title;

	/**
	 * Сохраняет подпись уровня для отчёта.
	 *
	 * @param title подпись на русском
	 */
	Level(String title) {
		this.title = title;
	}

	/**
	 * Возвращает подпись уровня.
	 *
	 * @return текст для отчёта и интерфейса
	 */
	public String title() {
		return title;
	}
}
